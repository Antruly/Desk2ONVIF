#pragma once

/**
 * @file src/common/exit_code.h
 * @brief 进程退出码。
 *
 * **单独一个头文件，因为它有两个互不相干的读者**：worker 侧（`main.cpp` 里
 * 那条常驻路径，决定自己退几）和 Service 侧（`service_host.cpp` 的看门狗，
 * 按这个数判断"该原地重拉还是该退避重拉"）。两边各写一个字面量 `7` 也能跑
 * —— 一直跑到有人改了其中一处为止。那时 `7` 会静默退化成"崩溃"，
 * 而崩溃**也会**重拉，于是症状只是"重启变慢了几秒"：没有报错、没有日志差异，
 * 唯一的下场是某天一个真正的崩溃循环被当成正常重启，没人去看日志。
 *
 * 所以这个数字只允许有一份定义。
 */

namespace d2o {

enum ExitCode {
  kExitOk = 0,
  /// 起了但失败了（端口被占、编码器建不起来）。看门狗会退避重拉。
  kExitFailed = 1,
  /// 参数/用法错误。**重拉没有意义** —— 同样的参数只会得到同样的错误，
  /// 而退避重拉会把它变成"每 30 秒打一遍同样的用法错误"的日志洪水。
  kExitUsage = 2,
  /// 「我要重启」。**这是唯一一个"成功意义上的非零"**：请求它的人
  /// （网页上的重启按钮 / 服务形态下的看门狗）等的就是这个数。
  ///
  /// 取 7 而不是 0：0 在服务里表示"正常结束、别再拉我了"，而重启恰恰是
  /// "立刻再拉我一次"。混用的话，服务形态下点重启 = 服务把自己关了。
  kExitRestart = 7,
};

}  // namespace d2o
